        if (profileTextAlign) profileTextAlign.className = "lg:col-span-2 text-center lg:text-left profile-text-align";
        if (footerDescAlign) footerDescAlign.className = "text-sm text-slate-400 leading-relaxed text-left footer-desc-align";
        if (contactArrow) contactArrow.setAttribute('data-lucide', 'arrow-right');
        if (mobileArrow) mobileArrow.setAttribute('data-lucide', 'arrow-right');
